// Read the supplied exports. Do not derive expected geometry from Flutter code.
const fs = require('node:fs');
const crypto = require('node:crypto');
const root = require('node:path').resolve(__dirname, '..');
const inputs = {
  home: 'C:/Users/pc/Downloads/Frame 1000004108 (1).svg',
  expressions: 'C:/Users/pc/Downloads/Group 427319317.svg',
  triggers: 'C:/Users/pc/AppData/Local/Temp/what made you feel this way.svg',
  coping: 'C:/Users/pc/AppData/Local/Temp/Group 427319318.svg',
};
const attrs = s => Object.fromEntries([...s.matchAll(/([\w:-]+)="([^"]*)"/g)].map(m => [m[1],m[2]]));
const catalogSource = fs.readFileSync(root+'/lib/core/data/mood_recording_catalog.dart','utf8');
const catalog = JSON.parse(catalogSource.match(/r'''([\s\S]*?)'''/)[1]);
const manifest = {version:1, width:375, typography:{family:'Outfit', source:'Production fallback: exported SVG text is outlined; font identity is not encoded.', chipSize:13, homeSize:12, headingSize:16}, sources:{}, collections:{}};
const names = {expressions:['Angry','Sad','Good','Upset','Spectacular','Happy'],triggers:['Work','School','Relationship','Sleep','Health','Life changes'],coping:['Coping Mechanisms']};
for(const [collection,path] of Object.entries(inputs)) {
  const svg = fs.readFileSync(path,'utf8');
  manifest.sources[collection] = {file:require('node:path').basename(path),sha256:crypto.createHash('sha256').update(svg).digest('hex'),...attrs(svg.match(/<svg\b[^>]*>/)[0])};
  const rects = [...svg.matchAll(/<rect\b[^>]*>/g)].map(m=>attrs(m[0]));
  if(collection==='home') {
    manifest.home = rects.filter(r=>r.height==='45').map((r,i)=>({slug:['angry','sad','good','upset','spectacular','happy'][i],x:+(r.x||0),y:0,width:+r.width,height:45,radius:+r.rx,fill:r.fill,art:{x:12,y:5,width:32,height:35},label:{x:54,y:14.5}}));
    continue;
  }
  const cards = [...svg.matchAll(/<path\b[^>]*>/g)].map(m=>attrs(m[0])).filter(p=>p.stroke==='#F5F5F5' && /^M\d+(?:\.\d+)? \d+(?:\.\d+)?H/.test(p.d)).map(p=>{
    const top=+p.d.match(/^M[\d.]+ ([\d.]+)/)[1];
    const ys=[...p.d.matchAll(/V([\d.]+)/g)].map(m=>+m[1]);
    const horizontal=[...p.d.matchAll(/H([\d.]+)/g)].map(m=>+m[1]);
    const x=horizontal.includes(352)?14:15;
    // The rounded path's bottom horizontal has the second-largest y ordinate.
    const all=p.d.match(/[-+]?\d*\.?\d+/g).map(Number);
    const bottom=Math.max(...all.filter(n=>n>=top && n>Math.max(...ys) && n<Math.max(...ys)+10));
    return {x,y:top-.5,width:346,height:bottom-top+1,radius:8};
  }).sort((a,b)=>a.y-b.y);
  const chips=rects.filter(r=>r.height==='28' && /^#[A-Fa-f0-9]{6}$/.test(r.fill||'') && !(collection==='coping' && r.x==='25' && r.y==='306')).map(r=>({x:+r.x,y:+r.y,width:+r.width,height:28,fill:r.fill}));
  if(collection==='coping') manifest.sources[collection].ignoredOverlappingBackground = {x:25,y:306,width:155,height:28,reason:'Extra background underneath the Watching a movie chip at y=308; not another choice.'};
  manifest.collections[collection]=cards.map((card,index)=>{
    const rows=chips.filter(c=>c.y>=card.y && c.y<card.y+card.height).sort((a,b)=>Math.abs(a.y-b.y)<=2?a.x-b.x:a.y-b.y);
    const options=collection==='expressions'?catalog.expressions.filter(o=>o.feeling_id===index+1):collection==='triggers'?catalog.triggers.filter(o=>o.group_name===names[collection][index]):catalog.coping;
    let unique=0;
    const mapped=rows.map((chip,i)=>{
      // The source duplicates Talking to a friend after Cooking. Keep it in
      // the independent manifest, but mark it as intentionally not rendered.
      const duplicate=collection==='coping' && i===12;
      const option=duplicate?catalog.coping.find(o=>o.slug==='talking-to-a-friend'):options[unique++];
      if(!option) throw new Error(`Unmapped ${collection} chip ${i}`);
      return {...chip,slug:option.slug,label:option.name,duplicate,art:{x:chip.x+8,y:chip.y+4,width:22,height:20}};
    });
    if(unique!==options.length) throw new Error(`Expected ${options.length} ${collection} choices, mapped ${unique}`);
    return {...card,name:names[collection][index],heading:{x:card.x+10,y:card.y+12,height:20},chips:mapped};
  });
}
fs.mkdirSync(root+'/assets/data',{recursive:true});
fs.mkdirSync(root+'/docs/design',{recursive:true});
fs.writeFileSync(root+'/assets/data/mood_reference.json',JSON.stringify(manifest,null,2)+'\n');
